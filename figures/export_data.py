"""Export the time series behind the figures as CSV and .mat.

IMPORTANT: these are outputs of the simplified Python models in this
folder (g10_model.py, freq_model.py, bus44_*_timing.py), NOT Simulink /
PSCAD results. They reproduce the figures exactly, but they must not be
reported as detailed-simulation data.
"""
import numpy as np
from scipy.io import savemat

import g10_model as gm
