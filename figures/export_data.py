NOTE = ("SYNTHETIC MODEL OUTPUT (Python reduced-order models in figures/), "
        "NOT Simulink results. Generated by export_data.py.")


def write(name, header_lines, cols):
    keys = list(cols)
    arr = np.column_stack([cols[k] for k in keys])
    with open(f"data/{name}.csv", "w") as fh:
        for line in [NOTE] + header_lines:
            fh.write(f"# {line}\n")
        fh.write(",".join(keys) + "\n")
        np.savetxt(fh, arr, delimiter=",", fmt="%.6g")
    savemat(f"data/{name}.mat", {**{k: np.asarray(v) for k, v in cols.items()},
                                 "note": NOTE,
                                 "description": " | ".join(header_lines)})
    print(f"data/{name}.csv/.mat  {arr.shape[0]} rows x {arr.shape[1]} cols")


